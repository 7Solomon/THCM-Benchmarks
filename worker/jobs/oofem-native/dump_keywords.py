#!/usr/bin/env python3
"""
dump_keywords.py -- regenerate prompts/oofem_records.md from the OOFEM build.

    OOFEM_ROOT=... OOFEM_BIN=... python worker/jobs/oofem-native/dump_keywords.py

The native counterpart of the oofem job's dump_api.py. That one lists what the
Python bindings export; this one lists what an input DECK may name: every
record keyword (`isole`, `transienttransport`, `tr1ht`, `gnuplot`, ...) that is
registered in the source AND compiled into this build.

    the NAMES come from `REGISTER_<Kind>(Class)` + `#define _IFT_<Class>_Name`
    the FILTER comes from the binary: a registration leaves a static
      `oofem::__dummy_<Class>` symbol in liboofem.so, so `nm` says which
      modules were actually built (fm/sm/tm here; am/mpm/pfem are not)

Keyword lists per record are NOT dumped -- ~2400 of them would drown the prompt.
The agent looks them up with `inspect_record`; the one-shot arm gets the names
and the enums it needs to ask for output.

The two enums at the end are what export modules are configured with:
`gpexportmodule vars 2 37 56` names InternalStateType numbers, and a `dm` file's
columns follow the node's DOF ids.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "prompts" / "oofem_records.md"

# Kinds a benchmark deck actually uses, in the order a deck names them.
KINDS = [
    ("EngngModel", "Analysis records (engineering models)"),
    ("ExportModule", "Export modules (listed after the analysis record, `nmodules N`)"),
    ("SparseNonLinearSystemNM", "Nonlinear solvers"),
    ("DofManager", "DOF managers (nodes)"),
    ("Element", "Elements"),
    ("CrossSection", "Cross sections"),
    ("Material", "Materials"),
    ("BoundaryCondition", "Boundary conditions and loads"),
    ("Function", "Time functions"),
    ("NonlocalBarrier", "Nonlocal barriers"),
    ("InitModule", "Init modules"),
    ("NodalRecoveryModel", "Nodal recovery models"),
]

REGISTER = re.compile(
    r"REGISTER_(\w+?)\s*\(\s*(\w+)\s*(?:,\s*(\w+)\s*)?\)")
NAME_DEF = re.compile(r'#define\s+_IFT_(\w+)_Name\s+"([^"]+)"')
ENUM_ITEM = re.compile(r"ENUM_ITEM_WITH_VALUE\(\s*(\w+)\s*,\s*(\d+)\s*\)")


def compiled_symbols(lib: Path) -> set | None:
    """Class names whose registration made it into the library, or None when
    that cannot be determined (no nm, no library) -- then nothing is filtered."""
    if not lib.is_file() or not shutil.which("nm"):
        return None
    r = subprocess.run(["nm", "-C", str(lib)], stdout=subprocess.PIPE,
                       stderr=subprocess.DEVNULL, text=True)
    syms = set()
    for ln in r.stdout.splitlines():
        m = re.search(r"oofem::__dummy_(\w+)$", ln)
        if m:
            syms.add(m.group(1))
    return syms or None


def scan(src: Path) -> tuple:
    names, regs = {}, []
    for path in src.rglob("*"):
        if path.suffix not in {".h", ".C", ".cpp", ".cc"} or not path.is_file():
            continue
        text = path.read_text(errors="replace")
        for cls, name in NAME_DEF.findall(text):
            names.setdefault(cls, name)
        if path.suffix != ".h":
            module = path.relative_to(src).parts[0]
            for kind, cls, alt in REGISTER.findall(text):
                if kind.startswith("_") or kind == "Material_Alt":
                    kind = "Material" if kind == "Material_Alt" else kind
                regs.append((kind, cls, alt, module))
    return names, regs


def enum(path: Path, prefix: str = "") -> list:
    if not path.is_file():
        return []
    return [(n, int(v)) for n, v in ENUM_ITEM.findall(path.read_text(errors="replace"))
            if n.startswith(prefix)]


def main() -> int:
    root = Path(os.environ.get("OOFEM_ROOT",
                               Path.home() / "Documents/Gereon/oofem/oofem-gw"))
    binary = Path(os.environ.get("OOFEM_BIN",
                                 Path.home() / "Documents/Gereon/oofem/build/debug/oofem"))
    src = root / "src"
    if not src.is_dir():
        sys.exit(f"no OOFEM source at {src}")
    built = compiled_symbols(binary.parent / "liboofem.so")
    names, regs = scan(src)

    groups: dict = {}
    dropped = 0
    for kind, cls, alt, module in regs:
        sym = cls + alt if alt else cls
        if built is not None and sym not in built:
            dropped += 1
            continue
        name = alt or names.get(cls)
        if not name:
            continue
        groups.setdefault(kind, {}).setdefault(module, set()).add((name, cls))

    lines = [
        "<!-- Generated by dump_keywords.py; regenerate, do not hand-edit. -->",
        "These are the record keywords this OOFEM build accepts. Keywords are",
        "case-insensitive. **A record name that is not listed here does not exist in",
        "this build**: OOFEM stops with `Couldn't create ...`.",
        "",
        "Each entry is `keyword (C++ class)`. The attributes a record takes are",
        "defined in the source as `#define _IFT_<Class>_<attr> \"<keyword>\"`,",
        "including those inherited from its base classes.",
        "",
    ]
    for kind, title in KINDS:
        mods = groups.get(kind)
        if not mods:
            continue
        lines.append(f"### {title}\n")
        for module in sorted(mods):
            entries = ", ".join(f"`{n}` ({c})" for n, c in
                                sorted(mods[module], key=lambda e: e[0].lower()))
            lines.extend(textwrap.wrap(f"- **{module}**: {entries}", width=100,
                                       subsequent_indent="  ",
                                       break_long_words=False,
                                       break_on_hyphens=False))
        lines.append("")

    ist = enum(src / "core" / "internalstatetype.h", "IST_")
    if ist:
        lines.append("### InternalStateType numbers (for `gpexportmodule vars`, `vtkxml vars`)\n")
        lines.extend(textwrap.wrap(
            ", ".join(f"{v} {n[4:]}" for n, v in ist), width=100))
        lines.append("")
    dof = [(n, v) for n, v in enum(src / "core" / "dofiditem.h") if 0 < v <= 14]
    if dof:
        lines.append("### DOF ids (`dofs` arrays of boundary conditions; column order in `dm` files)\n")
        lines.append(", ".join(f"{v} {n}" for n, v in dof))
        lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(len(s) for m in groups.values() for s in m.values())
    print(f"wrote {OUT}: {total} records"
          + (f", {dropped} registered but not compiled in" if built else
             " (no liboofem.so / nm: NOT filtered by the build)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
